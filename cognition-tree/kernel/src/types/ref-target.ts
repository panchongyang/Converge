/**
 * 引用边的种类与目标。
 *
 * 职责：定义引用的三种类型，以及树内节点 / 外部材料二选一的指向。
 * 边界：只描述边本身，不含引用 ID 和起点；外部材料只给定位符，不展开成另一棵树。
 * 协作：ref.ts 组出完整引用边；decision 的新节点草稿也用它描述待建引用。
 */
import type { NodeId } from './ids';

/** 引用边类型：依赖前提、同类实例、与事实冲突。少而固定，新增种类须先说明回答了什么新问题。 */
export type RefKind = 'premise' | 'example' | 'conflict';

/**
 * 引用目标，二选一：树内节点或外部材料。
 * 树内目标省略 part 指整个节点；外部材料只返回定位符，不展开成另一棵树。
 * part 的具体取值接口单未列举，这里保持字符串，实现查询时再定。
 * 对侧键写 `?: never`，让同时出现 nodeId 与 doc 的对象无法通过类型检查。
 */
export type RefTarget =
  | {
      /** 树内目标节点 ID。 */
      nodeId: NodeId;
      /** 节点局部（例如剪除理由）；省略指整个节点。 */
      part?: string;
      /** 外部材料与树内目标互斥。 */
      doc?: never;
    }
  | {
      /** 外部材料的仓库相对定位符。 */
      doc: string;
      /** 材料中的局部（例如文中实例）；省略指整份材料。 */
      part?: string;
      /** 树内目标与外部材料互斥。 */
      nodeId?: never;
    };
