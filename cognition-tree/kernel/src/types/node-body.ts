/**
 * 节点正文：标题、判断、依据与来源。
 *
 * 职责：描述新节点携带、保存后不再覆盖的文本事实。
 * 边界：缺项就不写；手稿未载时保留缺失，不补空串。正文一经保存不可覆盖，
 * 之后的纠偏只能新增勘误子节点。
 * 协作：node 的已保存节点、decision 的新节点草稿与 seed 的种子节点共用这一形状。
 */

export interface NodeBody {
  /** 一句话判断或问题，树上显示的标题；必填。 */
  title: string;
  /** 判断的展开内容（手稿的“内容”）。 */
  text?: string;
  /** 依据：为什么这样判断。 */
  basis?: string;
  /** 来源：判断出自哪里（手稿的“来源”）。 */
  source?: string;
  /** 未决原因：仅未决节点使用。 */
  openReason?: string;
  /** 确认来源说明：手稿状态行括注，例如“人类原话：……”。 */
  note?: string;
}
